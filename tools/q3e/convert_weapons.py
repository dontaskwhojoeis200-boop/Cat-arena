#!/usr/bin/env python3
"""N10-Q3E stage D part 3: converts the 16 N10 viewmodels (assets/n5/weapons/*.gun + *_base.jpg,
listed in assets/n5/weapon-assets.json) into Quake III MD3 models with their base textures, and
writes the cgame table of model names and muzzle points.

Model space as tools/q3e/mesh2md3.py: N10 (x, y, z) -> Quake III (y, -x, z) x 10 (the scale the
NAILGUN viewmodel was fitted with in stage C). The N10 muzzle points go through the same mapping.

Usage: convert_weapons.py [repo root]
"""
import json
import os
import subprocess
import sys

from PIL import Image

root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", ".."))
src = os.path.join(root, "assets", "n5", "weapons")
out = os.path.join(root, "game", "base", "catarena", "models", "catarena", "weapons")
header = os.path.join(root, "game", "ioq3", "code", "cgame", "cg_ca_weapon_models.h")
meta = json.load(open(os.path.join(root, "assets", "n5", "weapon-assets.json")))
SCALE = 10
os.makedirs(out, exist_ok=True)
rows = []
for w in sorted(meta["weapons"], key=lambda w: w["index"]):
    model, stem = w["model"], w["stem"]
    md3 = os.path.join(out, model + ".md3")
    shader = "models/catarena/weapons/" + model
    subprocess.run([sys.executable, os.path.join(root, "tools", "q3e", "mesh2md3.py"), os.path.join(src, stem + ".gun"), md3, shader, str(SCALE)], check=True)
    Image.open(os.path.join(src, stem + "_base.jpg")).convert("RGB").save(os.path.join(out, model + ".jpg"), quality=88)
    m = w["muzzle"]
    rows.append('\t{ "%s", { %.2ff, %.2ff, %.2ff } },\t// %d %s' % ("models/catarena/weapons/" + model + ".md3", m[1] * SCALE, -m[0] * SCALE, m[2] * SCALE, w["index"], w["weapon"]))
with open(header, "w", newline="\n") as f:
    f.write("// Generated by tools/q3e/convert_weapons.py from assets/n5/weapon-assets.json. Do not edit.\n")
    f.write("// Cat Arena viewmodels in N10 weapon order: model, muzzle point in model space (Quake III units).\n")
    f.write("static const struct { const char *model; float muzzle[3]; } caWeaponModels[CA_WEAPON_COUNT] = {\n")
    f.write("\n".join(rows) + "\n};\n")
print("converted %d weapons -> %s" % (len(rows), out))
