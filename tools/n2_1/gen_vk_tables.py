#!/usr/bin/env python3
"""Generates Vulkan command tables from the Khronos registry (vk.xml).

  gen_vk_tables.py <vk.xml> <out vk_command_table.inc> <out vulkan_baseline_imports.txt>

vk_command_table.inc : every Vulkan command with the core minor version that introduced it
                       (0 = 1.0, -1 = extension only) and the first extension that provides it.
                       Used by the device-simulation test layer to hide commands.
vulkan_baseline_imports.txt : commands the render library may import at link time
                       (Vulkan 1.0 + VK_KHR_surface + VK_KHR_swapchain). Everything newer must be
                       resolved at run time. Used by the import-symbol test.
Development tool only; not needed to build the game.
"""
import sys
import xml.etree.ElementTree as ET

def main():
    xml_path, table_path, imports_path = sys.argv[1:4]
    root = ET.parse(xml_path).getroot()
    core, ext = {}, {}
    for feature in root.findall('feature'):
        if 'vulkan' not in feature.get('api', 'vulkan').split(','):
            continue
        minor = int(feature.get('number').split('.')[1])
        for cmd in feature.findall('./require/command'):
            core.setdefault(cmd.get('name'), minor)
    for extension in root.findall('./extensions/extension'):
        if 'vulkan' not in extension.get('supported', '').split(','):
            continue
        for cmd in extension.findall('./require/command'):
            ext.setdefault(cmd.get('name'), extension.get('name'))
    names = sorted(set(core) | set(ext))
    with open(table_path, 'w') as out:
        out.write('// Generated by tools/n2_1/gen_vk_tables.py from Vulkan-Headers vk.xml (1.4.309). Do not edit.\n')
        out.write('// {command, core minor version (-1: extension only), providing extension or nullptr}\n')
        for n in names:
            e = ext.get(n)
            out.write('{"%s", %d, %s},\n' % (n, core.get(n, -1), '"%s"' % e if e else 'nullptr'))
    allowed = sorted(n for n in names if core.get(n) == 0 or ext.get(n) in ('VK_KHR_surface', 'VK_KHR_swapchain'))
    with open(imports_path, 'w') as out:
        out.write('\n'.join(allowed) + '\n')
    print(len(names), 'commands;', len(allowed), 'baseline imports;',
          sum(1 for n in names if core.get(n) == 3), 'core 1.3;', sum(1 for n in names if core.get(n) == 4), 'core 1.4')

main()
