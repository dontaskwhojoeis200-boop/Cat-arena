#!/usr/bin/env python3
"""Generates include/cat/generated/js_math_tables.inc: the double-double constants and tables of
cat/js_math.hpp (correctly rounded sin, cos, tan, atan2, pow).

Every value is computed with Python's decimal module at 400 significant digits from series whose
truncation error is far below 1e-90, then split into hi = nearest double, lo = nearest double to
(value - hi). Run: python3 tools/js_math/gen_tables.py > include/cat/generated/js_math_tables.inc
"""
from decimal import Decimal as D, getcontext

getcontext().prec = 400
EPS = D(10) ** -105


def arctan_inv(n):
    x = D(1) / n
    x2, s, t, k = x * x, x, x, 1
    while True:
        t *= -x2
        k += 2
        term = t / k
        if abs(term) < EPS:
            return s
        s += term


PI = 16 * arctan_inv(5) - 4 * arctan_inv(239)


def sin_cos(x):
    s, c, t, k = D(0), D(0), D(1), 0
    while abs(t) > EPS or k < 4:
        if k % 4 == 0:
            c += t
        elif k % 4 == 1:
            s += t
        elif k % 4 == 2:
            c -= t
        else:
            s -= t
        k += 1
        t = t * x / k
    return s, c


def atan(x):  # 0 <= x <= 1
    m = 1
    for _ in range(4):  # atan(x) = 2 atan(x / (1 + sqrt(1 + x^2)))
        x = x / (1 + (1 + x * x).sqrt())
        m *= 2
    s, t, k, x2, sign = D(0), x, 1, x * x, 1
    while abs(t) / k > EPS:
        s += sign * t / k
        t *= x2
        k += 2
        sign = -sign
    return m * s


def ln(x):
    return x.ln()


def exp(x):
    return x.exp()


def dd(v):
    hi = float(v)
    lo = float(v - D(hi))
    return hi, lo


def chunks(v, bits, count):
    """Splits v into `count` doubles of at most `bits` significant bits each (Cody-Waite)."""
    out = []
    for _ in range(count):
        e = 0  # 2^e <= |v| < 2^(e+1)
        while abs(v) >= D(2) ** (e + 1):
            e += 1
        while abs(v) < D(2) ** e:
            e -= 1
        unit = D(2) ** (e - bits + 1)
        c = (v / unit).to_integral_value() * unit
        f = float(c)
        assert D(f) == c, 'chunk not exact'
        out.append(f)
        v -= c
    return out


def h(x):
    return float(x).hex()


def emit_dd_array(name, values):
    print(f'inline constexpr dd {name}[] = {{')
    for v in values:
        hi, lo = dd(v)
        print(f'    {{{h(hi)}, {h(lo)}}},')
    print('};')


def emit_dd(name, v):
    hi, lo = dd(v)
    print(f'inline constexpr dd {name} = {{{h(hi)}, {h(lo)}}};')


print('// Generated by tools/js_math/gen_tables.py - do not edit. Double-double values (hi + lo).')
print('// NOLINTBEGIN')
emit_dd('kPi', PI)
emit_dd('kPiHalf', PI / 2)
emit_dd('kLn2', D(2).ln())
c = chunks(PI / 2, 33, 6)
print('// pi/2 in six chunks of at most 33 significant bits: k * chunk is exact for k < 2^20.')
print('inline constexpr double kPio2Chunk[] = {' + ', '.join(h(x) for x in c) + '};')
print('inline constexpr double kTwoOverPi = ' + h(2 / PI) + ';')

# sin / cos of j / 64, j = 0 .. 52 (covers |r| <= pi/4 + margin)
SIN, COS = [], []
for j in range(53):
    s, co = sin_cos(D(j) / 64)
    SIN.append(s)
    COS.append(co)
emit_dd_array('kSinTable', SIN)
emit_dd_array('kCosTable', COS)

fact = [D(1)]
for n in range(1, 30):
    fact.append(fact[-1] * n)
# sin t = t + t^3 * (S[0] + t^2 * (S[1] + ...)), S[k] = (-1)^(k+1) / (2k+3)!
emit_dd_array('kSinCoef', [(-1) ** (k + 1) / fact[2 * k + 3] for k in range(6)])
# cos t = 1 + t^2 * (C[0] + t^2 * (C[1] + ...)), C[k] = (-1)^(k+1) / (2k+2)!
emit_dd_array('kCosCoef', [(-1) ** (k + 1) / fact[2 * k + 2] for k in range(7)])

# atan(j / 64), j = 0 .. 64
emit_dd_array('kAtanTable', [atan(D(j) / 64) for j in range(65)])
# 1 / (2k + 3), k = 0 .. 8 (atan and atanh series)
emit_dd_array('kOddRecip', [D(1) / (2 * k + 3) for k in range(9)])

# ln(1 + j / 64), j = -19 .. 27
print('inline constexpr int kLnTableFirst = -19;')
emit_dd_array('kLnTable', [ln(1 + D(j) / 64) for j in range(-19, 28)])

# exp: 2^(j / 64), j = 0 .. 63; ln2 / 64 in three pieces (36, 36, 53 bits); 1 / n!, n = 2 .. 12
emit_dd_array('kExp2Table', [exp(D(j) / 64 * D(2).ln()) for j in range(64)])
l = chunks(D(2).ln() / 64, 36, 2)
rest = D(2).ln() / 64 - D(l[0]) - D(l[1])
print('inline constexpr double kLn2Over64Chunk[] = {' + ', '.join(h(x) for x in l + [float(rest)]) + '};')
print('inline constexpr double kSixtyFourOverLn2 = ' + h(64 / D(2).ln()) + ';')
emit_dd_array('kInvFact', [1 / fact[n] for n in range(2, 13)])
print('// NOLINTEND')
